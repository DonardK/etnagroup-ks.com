// One-time / re-runnable extraction of per-apartment specs from the floor-plan
// PDFs into client/src/data/apartmentSpecs.ts (keyed by the same pdfPath used in
// apartmentCatalog.ts). The chat assistant injects the matched apartment's specs
// on demand so it can answer room/layout questions accurately.
//
// Usage (from the client/ folder):
//   npm i -D pdf-parse
//   node scripts/extract-apartment-specs.mjs
//   npm remove pdf-parse   (optional cleanup; prod doesn't need it)

import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PDFParse } from 'pdf-parse'

const __dirname = fileURLToPath(new URL('.', import.meta.url))
const PUBLIC_DIR = join(__dirname, '..', 'public')
const PDF_ROOT = join(PUBLIC_DIR, 'Residences Apartments')
const OUT_FILE = join(__dirname, '..', 'src', 'data', 'apartmentSpecs.ts')

const ROOM_KEYWORDS = [
  ['Dhomë gjumi', /dhom[ëe]\s*(e\s*)?gjumi/i],
  ['Qëndrimi ditor', /q[ëe]ndrimi\s*ditor/i],
  ['Kuzhina/Tryezaria', /kuzhin/i],
  ['Banjo', /banjo/i],
  ['WC', /\bwc\b/i],
  ['Koridori', /kor+idori/i],
  ['Ballkoni', /ballkon/i],
  ['Terasë', /teras[ëe]/i],
  ['Tarracë', /tar+ac/i],
  ['Depo', /\bdepo\b/i],
]

const FLOOR_RE = /(parket|laminat|pllak[ëe]?\s*(qeramike|keramike)|qeramike|keramike)/i
const AREA_RE = /(?:sip|s)\.?\s*:\s*(\d+(?:[.,]\d+)?)\s*m\s*[²2]/i

const canonicalRoom = (text) => {
  for (const [name, re] of ROOM_KEYWORDS) {
    if (re.test(text)) return name
  }
  return null
}

const num = (s) => parseFloat(String(s).replace(',', '.'))

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) yield* walk(full)
    else if (entry.isFile() && entry.name.toLowerCase().endsWith('.pdf')) yield full
  }
}

function extractSpec(text) {
  const lines = text
    .split('\n')
    .map((l) => l.replace(/\s+/g, ' ').trim())
    .filter(Boolean)

  const spec = { rooms: [] }

  // Type, total area, green terrace
  const typeMatch = text.match(/TIPI:?\s*(\d)\s*\+\s*(\d)/i)
  if (typeMatch) spec.type = `${typeMatch[1]}+${typeMatch[2]}`

  const totalMatch = text.match(
    /SIP[ËE]RFAQJA\s+E\s+BANES[ËE]S(?:\s*\+\s*BALLKONI)?\s*[:=]\s*(\d+(?:[.,]\d+)?)\s*m/i,
  )
  if (totalMatch) spec.totalArea = num(totalMatch[1])

  const greenMatch = text.match(/TARRACA\s+E\s+GJEL[BË]RUAR\s*:?\s*(\d+(?:[.,]\d+)?)\s*m/i)
  if (greenMatch) spec.greenTerrace = num(greenMatch[1])

  // Rooms: find area markers, attach the nearest clean room keyword.
  const seen = new Set()
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(AREA_RE)
    if (!m) continue
    const area = num(m[1])
    if (!Number.isFinite(area) || area <= 0 || area > 80) continue

    const before = lines[i].slice(0, m.index)
    let room = canonicalRoom(before)
    if (!room && i > 0) room = canonicalRoom(lines[i - 1])
    if (!room && i > 1) room = canonicalRoom(lines[i - 2])
    if (!room) continue

    const floorText = `${lines[i]} ${lines[i + 1] ?? ''}`
    const floorMatch = floorText.match(FLOOR_RE)
    const floor = floorMatch ? floorMatch[1] : undefined

    const key = `${room}-${area}`
    if (seen.has(key)) continue
    seen.add(key)
    spec.rooms.push(floor ? { name: room, area, floor } : { name: room, area })
  }

  spec.rooms = spec.rooms.map((r) => {
    // Laminate "bathrooms" this large are almost always a misread bedroom.
    if (r.name === 'Banjo' && r.floor && /laminat/i.test(r.floor) && r.area >= 8) {
      return { ...r, name: 'Dhomë gjumi' }
    }
    return r
  })

  // Drop OCR/layout misreads: tiny "bedrooms" (usually WC) and huge "storage"
  // rooms that copied the living-room area.
  spec.rooms = spec.rooms.filter((r) => {
    if (r.name === 'Dhomë gjumi' && r.area < 5) return false
    if (r.name === 'Depo' && r.area > 15) return false
    return true
  })

  if (!spec.type) {
    const beds = spec.rooms.filter((r) => r.name === 'Dhomë gjumi').length
    if (beds > 0) spec.type = `${beds}+1`
  }

  return spec
}

const main = async () => {
  const result = {}
  let count = 0
  let withRooms = 0

  for await (const file of walk(PDF_ROOT)) {
    const rel = relative(PUBLIC_DIR, file).split(sep).join('/')
    try {
      const buf = await readFile(file)
      const parser = new PDFParse({ data: new Uint8Array(buf) })
      const { text } = await parser.getText()
      await parser.destroy()
      const spec = extractSpec(text)
      result[rel] = spec
      count++
      if (spec.rooms.length > 0) withRooms++
    } catch (err) {
      console.warn(`! Failed to parse ${rel}: ${err.message}`)
      result[rel] = { rooms: [] }
    }
  }

  const sortedKeys = Object.keys(result).sort()
  const ordered = {}
  for (const k of sortedKeys) ordered[k] = result[k]

  const banner =
    '// AUTO-GENERATED by scripts/extract-apartment-specs.mjs — do not edit by hand.\n' +
    '// Re-run the script after adding/replacing apartment PDFs.\n\n'

  const body =
    'export interface ApartmentRoom {\n' +
    '  name: string\n' +
    '  area: number\n' +
    '  floor?: string\n' +
    '}\n\n' +
    'export interface ApartmentSpec {\n' +
    '  type?: string\n' +
    '  totalArea?: number\n' +
    '  greenTerrace?: number\n' +
    '  rooms: ApartmentRoom[]\n' +
    '}\n\n' +
    `export const apartmentSpecs: Record<string, ApartmentSpec> = ${JSON.stringify(
      ordered,
      null,
      2,
    )}\n`

  await writeFile(OUT_FILE, banner + body, 'utf8')
  console.log(`Parsed ${count} PDFs (${withRooms} with room breakdowns).`)
  console.log(`Wrote ${OUT_FILE}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
